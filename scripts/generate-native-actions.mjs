import { mkdir, writeFile } from "node:fs/promises"
import path from "node:path"
import { fileURLToPath } from "node:url"
import { NATIVE_ACTIONS } from "../lib/native-action-contract.mjs"

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const output = path.join(root, "native/generated-actions")
await mkdir(output, { recursive: true })
for (const [module, actions] of Object.entries(NATIVE_ACTIONS)) {
  // Type-only references preserve every original PWA function signature.
  // No server implementation enters the offline/static native bundle.
  const source = [
    '// Generated by scripts/generate-native-actions.mjs. Do not edit.',
    'import { nativeAction } from "../native-action"',
    `type Actions = typeof import("../../app/actions/${module}")`,
    `export type * from "../../app/actions/${module}"`,
    ...actions.map((action) =>
      `export const ${action} = nativeAction<Actions["${action}"]>("${module}", "${action}")`),
    "",
  ].join("\n")
  await writeFile(path.join(output, `${module}.ts`), source)
}
console.log(`Prepared ${Object.keys(NATIVE_ACTIONS).length} shared PWA action adapters.`)
